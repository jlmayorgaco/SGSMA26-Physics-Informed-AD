    var = pd.read_csv(var_path).sort_values("channel").variance.to_numpy(float)
    horizons = [30, 45, 60, 90, 120]
    out, eta = [], []
    for op, _, state_tag, cond_tag in OPS:
        rr = src / op / "physical" / "results"; arr = corrected[op][0]
        if not rr.exists(): continue
        base_candidates = list(rr.glob("PAIR_3_4_AIm0p0_AJ0p0_R1.csv"))
        if not base_candidates: continue
        base_fp = rr / "PAIR_3_4_AIm0p0_AJ0p0_R1.csv"
        y0 = (__import__("scripts.t120_op_conditioned_manifold_closure_v1", fromlist=["load_bank"]).load_bank(base_fp, rows)
              if base_fp.exists() else None)
        olddir = PD / "output" / "second_order_op_robustness_v1" / cond_tag / "results"
        Dold = pd.read_csv(olddir / "analytic_D_all.csv", header=None).to_numpy(float)
        Qold = pd.read_csv(olddir / "analytic_Q_self_all.csv", header=None).to_numpy(float)
        QCold = pd.read_csv(olddir / "analytic_Q_cross_all.csv", header=None).to_numpy(float)
        oldarr = {"D": Dold, "Q": Qold, "Qcross": QCold}
        for fp in sorted(rr.glob("PAIR_*.csv")):
            parsed = _parse_physical_name(fp)
            if parsed is None: continue
            i, j, ai, aj = parsed
            y = __import__("scripts.t120_op_conditioned_manifold_closure_v1", fromlist=["load_bank"]).load_bank(fp, rows)
            if i == 3 and j == 4 and abs(ai) < 1e-15 and abs(aj) < 1e-15: continue
            if y0 is None: continue
            target = y - y0; support = (i, j) if j else (i,)
            if j == 0:  # single-event files are retained as controls
                support = (i,); aj = 0.0
            for h in horizons:
                n = 32 * h
                mu_c = _model_array(arr, support, ai, aj, h)
                # Historical OP-conditioned dictionary is the uncorrected
                # comparator; corrected arrays differ only by the exact t1
                # state-map mismatch propagated homogeneously.
                mu_o = _model_array(oldarr, support, ai, aj, h)
                for lab, mu in (("old_conditioned", mu_o), ("corrected_conditioned", mu_c)):
                    err = target[:n] - mu
                    out.append({"op_tag": op, "pair": f"{i}-{j}", "ai": ai, "aj": aj, "horizon": h, "model": lab,
                                "raw_relative_error": float(np.linalg.norm(err) / max(np.linalg.norm(target[:n]), 1e-30)),
                                "whitened_error": float(np.linalg.norm(_ar1_whiten(err, var))), "cosine": cos(target[:n], mu),
                                "source": "stored_TDS_bank", "new_tds_generated": False})
                # Eta uses the corrected local model and a linear profiled
                # competing-manifold margin, exactly as the historical closure.
                prof, ct, cs = _profile_fast(mu_c, arr["D"], var, h, support)
                eta.append({"op_tag": op, "pair": f"{i}-{j}", "ai": ai, "aj": aj, "horizon": h,
                            "eta_old": float(np.linalg.norm(_ar1_whiten(target[:n] - mu_o, var)) / math.sqrt(max(_profile_fast(mu_o, Dold, var, h, support)[0], 1e-30))),
                            "eta_corrected": float(np.linalg.norm(_ar1_whiten(target[:n] - mu_c, var)) / math.sqrt(max(prof, 1e-30))),
                            "margin_corrected_sq": prof, "nearest_competitor": ct + ":" + "-".join(map(str, cs)), "new_tds_generated": False})
    return pd.DataFrame(out), pd.DataFrame(eta)


