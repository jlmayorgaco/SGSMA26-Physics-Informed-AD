def _all_maps(op: str) -> list[Path]:
    out = []
    for p in sorted((MAP / op).glob("*.csv")):
        if p.name in {"baseline.csv", "manifest.csv", "state_manifest.csv"}:
            continue
        try:
            if len(_csv_vec(p)) == 192:
                out.append(p)
        except Exception:
            pass
    return out


def _self_derivatives(op: str, b: int):
    base = _csv_vec(MAP / op / "baseline.csv")
    p5, m5 = _csv_vec(map_path(op, "self", b, None, H5, 0.0)), _csv_vec(map_path(op, "self", b, None, -H5, 0.0))
    p2, m2 = _csv_vec(map_path(op, "self", b, None, H2, 0.0)), _csv_vec(map_path(op, "self", b, None, -H2, 0.0))
    d5, d2 = (p5 - m5) / (2 * H5), (p2 - m2) / (2 * H2)
    q5, q2 = (p5 - 2 * base + m5) / H5**2, (p2 - 2 * base + m2) / H2**2
    return (4 * d2 - d5) / 3, (4 * q2 - q5) / 3, np.linalg.norm(d2 - d5), np.linalg.norm(q2 - q5)


def _cross_derivative(op: str, i: int, j: int, h: float) -> np.ndarray:
    vals = {}
    for si, sj in ((1, 1), (1, -1), (-1, 1), (-1, -1)):
        vals[(si, sj)] = _csv_vec(map_path(op, "cross", i, j, si * h, sj * h))
    return (vals[(1, 1)] - vals[(1, -1)] - vals[(-1, 1)] + vals[(-1, -1)]) / (4 * h * h)


def _cross_derivatives(op: str, i: int, j: int):
    c5, c2 = _cross_derivative(op, i, j, H5), _cross_derivative(op, i, j, H2)
    return (4 * c2 - c5) / 3, np.linalg.norm(c2 - c5)


