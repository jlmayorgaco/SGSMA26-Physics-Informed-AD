def _state_to_output(v: np.ndarray, C: np.ndarray) -> np.ndarray:
    return C @ v


def _reduced(A: np.ndarray, M: np.ndarray):
    # State exports are ordered algebraic first, differential second in the
    # native metadata.  The descriptor reduction is A_dd-A_da A_aa^-1 A_ad.
    alg = np.flatnonzero(np.isclose(np.diag(M), 0.0))
    dif = np.flatnonzero(~np.isclose(np.diag(M), 0.0))
    Aaa, Aad, Ada, Add = A[np.ix_(alg, alg)], A[np.ix_(alg, dif)], A[np.ix_(dif, alg)], A[np.ix_(dif, dif)]
    As = Add - Ada @ np.linalg.solve(Aaa, Aad)
    return alg, dif, As, Aaa, Aad


def _propagate(e: np.ndarray, nframes: int, A: np.ndarray, M: np.ndarray):
    alg, dif, As, Aaa, Aad = _reduced(A, M)
    ed = e[dif]
    E = expm(As * DT)
    out = np.zeros((nframes, len(e)))
    # Dictionary row 0 is the callback-time/pre-event baseline.  The exact
    # production map is first observed at row 1 (t1=tau+dt), so the mismatch
    # must not be injected one sample early.
    for k in range(nframes):
        if k == 0:
            continue
        edk = np.linalg.matrix_power(E, k - 1) @ ed
        eak = -np.linalg.solve(Aaa, Aad @ edk)
        out[k, dif], out[k, alg] = edk, eak
    return out


def _build_corrected_dictionaries(op: str, state_tag: str, cond_tag: str, validation_rows, first_rows, second_rows):
    A, M, order, C = _read_meta(state_tag)
    olddir = PD / "output" / "second_order_op_robustness_v1" / cond_tag / "results"
    D = pd.read_csv(olddir / "analytic_D_all.csv", header=None).to_numpy(float)
    Q = pd.read_csv(olddir / "analytic_Q_self_all.csv", header=None).to_numpy(float)
    QC = pd.read_csv(olddir / "analytic_Q_cross_all.csv", header=None).to_numpy(float)
    arrays = {"D": D.copy(), "Q": Q.copy(), "Qcross": QC.copy()}
    for b in BUSES:
        ex = validation_rows[(validation_rows.op_tag == op) & (validation_rows.direction == f"self_{b}") & (validation_rows.derivative_order == 1)]
        if len(ex):
            e1 = _state_export(state_tag, f"state_first_self_{b}.csv")
            old1 = _state_export(state_tag, f"state_first_self_{b}.csv")
            # The producer's state_first is the variational instantaneous
            # map; the Richardson vector is the exact production map.
            exact1 = ex.iloc[0]["_vec_exact"]
            corr = _propagate(exact1 - old1, 120, A, M)
            arrays["D"][:, BUSES.index(b)] += np.asarray([C @ x for x in corr]) .reshape(-1)
    # For second order the state export is the raw u_ij.  Self Q carries the
    # Taylor 1/2 coefficient, while cross Qij carries the raw mixed term.
    for b in BUSES:
        ex = validation_rows[(validation_rows.op_tag == op) & (validation_rows.direction == f"self_{b}") & (validation_rows.derivative_order == 2)]
        if len(ex):
            old2 = _state_export(state_tag, f"state_second_self_{b}.csv")
            exact2 = ex.iloc[0]["_vec_exact"]
            corr = _propagate(exact2 - old2, 120, A, M)
            arrays["Q"][:, BUSES.index(b)] += 0.5 * np.asarray([C @ x for x in corr]).reshape(-1)
    for k, (i, j) in enumerate(PAIRS):
        ex = validation_rows[(validation_rows.op_tag == op) & (validation_rows.direction == f"cross_{i}_{j}") & (validation_rows.derivative_order == 2)]
        if len(ex):
            old2 = _state_export(state_tag, f"state_second_cross_{i}_{j}.csv")
            exact2 = ex.iloc[0]["_vec_exact"]
            corr = _propagate(exact2 - old2, 120, A, M)
            arrays["Qcross"][:, k] += np.asarray([C @ x for x in corr]).reshape(-1)
    out = RES / f"corrected_dictionary_{op}.npz"
    np.savez_compressed(out, **arrays)
    return arrays, A, M, C


def _profile_fast(y: np.ndarray, D: np.ndarray, var: np.ndarray, horizon: int, support: tuple[int, ...]):
    """Profile a linear competing signature with precomputed small solves."""
    yw = _ar1_whiten(y[:32*horizon], var)
    best = (float("inf"), "", ())
    for b in BUSES:
        if b in support:
            continue
        A = _ar1_whiten(D[:32*horizon, BUSES.index(b)], var)
        aa = float(A @ yw / max(A @ A, 1e-30)); val = float(np.sum((yw - A * aa) ** 2))
        if val < best[0]: best = (val, "single", (b,))
    for sp in PAIRS:
        if set(sp) == set(support):
            continue
        A = np.column_stack([_ar1_whiten(D[:32*horizon, BUSES.index(b)], var) for b in sp])
        aa = np.linalg.lstsq(A, yw, rcond=1e-12)[0]; val = float(np.sum((yw - A @ aa) ** 2))
        if val < best[0]: best = (val, "double", sp)
    return best


def _ar1_whiten(x: np.ndarray, var: np.ndarray, rho: float = 0.3512083596) -> np.ndarray:
    x = np.asarray(x, float).reshape(-1, 32); s = np.sqrt(np.maximum(var, 1e-30)); z = np.empty_like(x)
    z[0] = x[0] / s
    if len(x) > 1: z[1:] = (x[1:] - rho * x[:-1]) / (s * np.sqrt(1 - rho * rho))
    return z.reshape(-1)


def _model_array(arr: dict, support: tuple[int, ...], ai: float, aj: float, nframes: int) -> np.ndarray:
    D, Q, QC = arr["D"], arr["Q"], arr["Qcross"]
    i, n = BUSES.index(support[0]), 32 * nframes
    out = ai * D[:n, i] + ai * ai * Q[:n, i]
    if len(support) > 1:
        j = BUSES.index(support[1])
        out = out + aj * D[:n, j] + aj * aj * Q[:n, j] + ai * aj * QC[:n, PAIRS.index(tuple(sorted(support)))]
    return out


def _parse_physical_name(fp: Path):
    m = re.match(r"PAIR_(\d+)_(\d+)_AI([m\d\.p]+)_AJ([m\d\.p]+)_R1", fp.stem)
    if not m:
        return None
    def pa(s): return float(s.replace("m", "-").replace("p", "."))
    return int(m.group(1)), int(m.group(2)), pa(m.group(3)), pa(m.group(4))


def _physical_replay(corrected):
    """Replay all existing TDS trajectories against old and corrected maps."""
