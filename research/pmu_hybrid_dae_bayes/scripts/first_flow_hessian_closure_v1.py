def _csv_vec(path: Path) -> np.ndarray:
    d = pd.read_csv(path)
    cols = [c for c in d.columns if re.fullmatch(r"u\d+|x\d+", str(c))]
    if not cols:
        # State exports have x1..x192 without a metadata row in some versions.
        cols = [c for c in d.columns if str(c).startswith(("u", "x"))]
    return d[cols].iloc[-1].to_numpy(float)


def _token(x: float) -> str:
    return str(x).replace("-", "m").replace(".", "p")


def map_path(op: str, kind: str, i: int, j: int | None, ai: float, aj: float) -> Path:
    stem = f"{kind}_{i}" + (f"_{j}" if j is not None else "") + f"_ai{_token(ai)}_aj{_token(aj)}.csv"
    return MAP / op / stem


def rel(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.linalg.norm(a - b) / max(np.linalg.norm(a), 1e-30))


def cos(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.dot(a, b) / max(np.linalg.norm(a) * np.linalg.norm(b), 1e-30))


