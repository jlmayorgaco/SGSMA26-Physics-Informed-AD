    event_noise=noise_df[noise_df.regime!="H0"].groupby("case_id",sort=False).head(N_INFER)
    for n,r in enumerate(event_noise.itertuples()):
        rr=load_obs(r.physical_path,yn,idx,rows); rw=wht(rr+noise(r.noise_seed),L); q=infer_case(rw,int(r.source_i),int(r.source_j),float(r.amplitude_i),float(r.amplitude_j),Dw,Qw,qijw,level=level)
        q.update({"case_id":r.case_id,"source_i":r.source_i,"source_j":r.source_j,"amplitude_i":r.amplitude_i,"amplitude_j":r.amplitude_j,"regime":r.regime,"noise_seed":r.noise_seed,"level":level}); out.append(q)
    return out

